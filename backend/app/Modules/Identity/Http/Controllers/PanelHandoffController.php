<?php

declare(strict_types=1);

namespace App\Modules\Identity\Http\Controllers;

use App\Http\Controllers\Controller;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\Cache;
use Illuminate\Support\Str;

/**
 * الجسرُ بينَ مفتاحَينِ مختلفَين.
 *
 * ⛔ **مسؤولُ المنصّةِ كانَ يكتبُ كلمةَ سرِّه مرّتَين، ولم يكنْ ذلك عطلاً بل
 * نتيجةَ تصميمٍ مكتوب**: الواجهةُ تُصادَقُ برمزِ Sanctum في `localStorage`،
 * و`‎/admin` لوحةُ Laravel بجلسةٍ وكوكي. و`localStorage` **لا يسافرُ مع طلبِ
 * صفحة** — هو مخزنُ جافاسكربت لا ترويسة — فالطلبُ يصلُ اللوحةَ بلا إثباتٍ
 * إطلاقاً، وحارسُ الجلسةِ يرى زائراً مجهولاً ويسألُه من جديد. ووثيقةُ
 * `UserResource` تقولُها بنصِّها عندَ `may_access_admin_panel`: «هذا الحقلُ لا
 * يفتحُ شيئاً».
 *
 * فالحلُّ تذكرةٌ تُصرَفُ مرّة: الواجهةُ تسألُ **بالمفتاحِ الذي تملكُه**، والخادمُ
 * يصنعُ لها المفتاحَ الآخَر.
 *
 * ⚠️ **ولا يُنقَلُ المنتَجُ كلُّه إلى كوكي بدلَ ذلك، وهو الحلُّ «الأنظفُ» ظاهراً.**
 * حدُّ الأجهزةِ (٠٠٤) مبنيٌّ بأكملِه على أنّ ثمّةَ **رمزاً** يُحذَفُ فيموتُ جهازٌ
 * بعينِه — «الرقمُ الوحيدُ الذي لا يستطيعُ العميلُ تزويرَه» بنصِّ `CLAUDE.md`.
 * وبالكوكي لا رمزَ أصلاً، فيسقطُ الحدُّ ونبضةُ الجرسِ التي تكتشفُ الطردَ معه.
 * حارسٌ مشحونٌ يعملُ، لا كودٌ ميّت.
 *
 * والأمانُ هنا في التفاصيل، وكلُّ واحدةٍ منها تُغلِقُ باباً بعينِه — انظر كلَّ
 * سطرٍ أدناه.
 */
class PanelHandoffController extends Controller
{
    /** مفتاحُ التذكرةِ في المخبأ. */
    private const PREFIX = 'panel-handoff:';

    /**
     * ثوانٍ. الرحلةُ ضغطةٌ واحدة، فلا سببَ لعمرٍ أطول — والنافذةُ هي كلُّ ما
     * يملكُه مَن تسرّبَت إليه التذكرةُ من سجلِّ متصفّحٍ أو وكيل.
     */
    private const TTL = 60;

    /**
     * التذكرة — تُطلَبُ بالمفتاحِ القائمِ (رمزُ Sanctum) ولا شيءَ غيرِه.
     *
     * ⚠️ **المستخدِمُ من الطلبِ المُصادَقِ عليه، ولا يُقرَأُ معرَّفٌ من المتنِ
     * إطلاقاً.** تذكرةٌ تقبلُ «سجّلْني بوصفي كذا» ليست جسراً بل بوّابةَ تصعيدِ
     * صلاحيّاتٍ كاملة.
     *
     * ⚠️ **والشرطُ `mayAccessAdminPanel()` نفسُها، لا نسخةً منها.** هذا الملفُّ
     * هو ثالثُ قارئٍ للسؤالِ بعدَ `EnsureFilamentAccess` و`canAccessPanel()`،
     * وذلك الوسيطُ يحملُ في وثيقتِه تحذيراً من هذا بعينِه: «هجاءان لسؤالٍ واحدٍ
     * يتباعدانِ عندَ أوّلِ دورٍ يُضاف، فيُسمَحُ عندَ بابٍ ويُمنَعُ عندَ الآخر».
     */
    public function mint(Request $request): JsonResponse
    {
        /** @var User $user */
        $user = $this->currentUser($request);

        if (! $user->mayAccessAdminPanel()) {
            return new JsonResponse([
                'message' => 'هذه اللوحة ليست من صلاحيّاتك.',
                'code' => 'panel_forbidden',
            ], 403);
        }

        // ⚠️ عشوائيٌّ معتِمٌ لا يحملُ معنى. لا معرَّفَ ولا وقتَ انتهاءٍ مُرمَّزٌ
        // فيه: العمرُ في المخبأِ على الخادم، فلا شيءَ يُقرَأُ من التذكرةِ ولا
        // شيءَ يُزوَّرُ فيها — ولذلك لا توقيعَ عليها: التوقيعُ يحمي وسائطَ لا
        // وجودَ لها هنا.
        $ticket = Str::random(64);

        Cache::put(self::PREFIX.$ticket, $user->getKey(), self::TTL);

        activity()
            ->causedBy($user)
            ->withProperties(['ip' => $request->ip()])
            ->event('panel_handoff_requested')
            ->log('طلب دخول لوحة الإدارة من الواجهة');

        return new JsonResponse([
            'url' => route('panel.handoff.enter', ['ticket' => $ticket]),
            'expires_in' => self::TTL,
        ]);
    }

    /**
     * الصرف — مرّةً واحدة، ثمّ إلى اللوحة.
     *
     * ⚠️ **`Cache::pull` لا `get`**: التذكرةُ تُمحى وهي تُقرَأ. تذكرةٌ تُعادُ
     * تُقرَأُ من سجلِّ المتصفّحِ أو من سجلِّ وكيلٍ فيصيرُ قارئُها مسؤولَ منصّة.
     * (وسباقُ طلبَينِ متزامنَينِ على التذكرةِ نفسِها لا يضرُّ: كلاهما يُسجِّلُ
     * **الشخصَ نفسَه**، فليسَ ثمّةَ جوابانِ مختلفان.)
     *
     * ⚠️ **ومعرِّفُ الجلسةِ يُولَّدُ من جديدٍ عندَ الدخول، بلا سطرٍ لنا.** بدونِ
     * ذلك يُثبِّتُ مهاجمٌ معرِّفَ جلسةٍ يعرفُه في متصفّحِ الضحيّة، ثمّ «يُرقّيه»
     * هذا الجسرُ إلى جلسةِ مسؤول — وهي ثغرةُ تثبيتِ الجلسةِ بحرفِها. والذي
     * يمنعُها `SessionGuard::login()` نفسُها: أوّلُ ما تفعلُه `updateSession()`
     * وهي `regenerate(true)` — توليدٌ **وإتلافٌ للقديم**.
     *
     * وكانَ هنا `session()->regenerate()` مكتوبةً بعدَها. لم تكن تزيدُ شيئاً
     * (وهي أضعف: لا تُتلِفُ القديم)، وكانت تكسِرُ تسجيلَ ٠٣٧ · قصّة ٢ — انظرِ
     * السببَ كاملاً عندَ سطرِ الدخولِ في متنِ الدالّة.
     *
     * ⚠️ **والوجهةُ مكتوبةٌ هنا، ولا تُقرَأُ من الطلبِ أبداً.** وسيطُ `next`
     * على رابطٍ يحملُ نطاقَنا الموثوقَ يحوّلُ الجسرَ إلى أداةِ تصيّدٍ جاهزة.
     *
     * ⚠️ **والشرطُ يُسألُ مرّةً ثانيةً هنا**: بينَ الطلبِ والصرفِ ستّونَ ثانيةً،
     * وسحبُ صلاحيّةٍ داخلَها يجبُ أن يُغلِقَ البابَ لا أن يسبقَه.
     */
    public function enter(Request $request, string $ticket): RedirectResponse
    {
        $userId = Cache::pull(self::PREFIX.$ticket);

        /*
        | `whereKey(...)->first()` لا `find()`: الثانيةُ تقبلُ مصفوفةً فيتّسعُ
        | نوعُها إلى `User|Collection`، وكلُّ سطرٍ بعدَها يصيرُ ادّعاءً لا يقرؤُه
        | المحلّل. والقيمةُ آتيةٌ من المخبأِ فنوعُها `mixed` أصلاً.
        */
        $user = $userId === null ? null : User::query()->whereKey($userId)->first();

        if ($user === null || ! $user->mayAccessAdminPanel()) {
            // واحدةٌ لكلِّ الأسباب: انتهت، أو صُرِفَت، أو لم توجدْ قطّ، أو سُحبت
            // الصلاحيّة. جوابٌ يميّزُ بينَها يخبرُ مَن يجرّبُ متى يقتربُ.
            abort(403, 'انتهت صلاحيّة هذا الرابط أو استُخدم من قبل. افتح اللوحة من حسابك مرّة أخرى.');
        }

        /*
        | ⚠️ **ولا `session()->regenerate()` بعدَها، وكانت هنا.** `SessionGuard::login()`
        | يستدعي `updateSession()` وهي `regenerate(true)` — تُولِّدُ معرِّفاً جديداً
        | **وتُتلِفُ القديم**، أي دفاعُ تثبيتِ الجلسةِ كاملاً وأقوى من `regenerate()`
        | المجرَّدةِ التي كانت تليها. فالسطرُ لم يكن يزيدُ أماناً.
        |
        | وكانَ يكسِرُ شيئاً: حدثُ `Login` يُطلَقُ **داخلَ** `login()` بعدَ التوليد،
        | و`RecordPanelSignIn` يسجّلُ المعرِّفَ الذي يراه لحظتَها. توليدٌ ثانٍ بعدَه
        | يتركُ الصفَّ مشيراً إلى جلسةٍ لم تعدْ موجودة — صفٌّ يبدو سليماً ولا يُنهي
        | شيئاً، وهو عينُ العطبِ الذي تُغلِقُه ٠٣٧ · قصّة ٢.
        |
        | و`PanelSessionRecordedTest` يرسبُ إن عادَ السطر.
        */
        Auth::guard('web')->login($user);

        activity()
            ->causedBy($user)
            ->withProperties(['ip' => $request->ip()])
            ->event('panel_handoff_used')
            ->log('دخل لوحة الإدارة عبر جسر الواجهة');

        return redirect()->to(config('filament.path', 'admin'));
    }
}
