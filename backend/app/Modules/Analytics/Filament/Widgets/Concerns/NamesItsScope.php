<?php

declare(strict_types=1);

namespace App\Modules\Analytics\Filament\Widgets\Concerns;

use App\Shared\Support\WorkspaceContext;

/**
 * ⛔ **ويدجتٌ واحدٌ يعني شيئَينِ بحسبِ من يقرؤه، ولافتةٌ واحدةٌ تصفُ أحدَهما.**
 *
 * `EnrollmentStatsWidget` و`ExamStatsWidget` لا تتخطّيانِ نطاقَ المساحة، ولا
 * تحتاجانِ ذلك: لمدرّسٍ يقرآنِ أرقامَ مساحتِه، وهو الصحيح. لكنّ
 * `WorkspaceScope::apply()` **لا يُضيفُ شرطاً حينَ يكونُ المعرِّفُ فارغاً**، ومديرُ
 * المنصّةِ الذي لا `last_workspace_id` عندَه يقرأُ بالضبطِ مجاميعَ المنصّةِ كلِّها
 * من الويدجتِ نفسِه — تحتَ لافتةِ «إجمالي التسجيلات» التي لا تقولُ أيَّهما.
 *
 * ⚠️ **والتعليقُ الذي كتبتُه فوقَهما أوّلَ مرّةٍ كان يقولُ «هذان أرقامُ مساحةِ
 * القارئِ نفسِه» — وهو نصفُ الحقيقة**، أي الشكلُ الذي يجعلُ القارئَ التالي يبني
 * عليه. الفرقُ صارَ في اللافتةِ نفسِها بدلَ أن يبقى في رأسِ من كتب.
 *
 * ⚠️ ولا يُصلَحُ بتخطّي النطاقِ ولا بإخفاءِ الويدجتِ عن المدير: الأوّلُ يسلبُ
 * المدرّسَ أرقامَه، والثاني يسلبُ المديرَ إحصاءَ الاختباراتِ الذي لا بديلَ له في
 * ويدجتاتِ المنصّة. السؤالُ ليس «أيُّ رقمٍ نعرض» بل «هل يعرفُ القارئُ أيَّ رقمٍ
 * يرى».
 */
trait NamesItsScope
{
    /**
     * «على المنصّة» أو «في مساحتك» — من السياقِ الذي سيقرأُ به الاستعلامُ نفسُه.
     *
     * ⚠️ يُقرَأُ عندَ التصييرِ لا عندَ الإنشاء: `WorkspaceContext` مفردةٌ تُحلُّ
     * كسولاً، وقراءةٌ مبكّرةٌ تُجمِّدُ الجوابَ قبلَ أن تُحلَّ الجلسة.
     */
    protected function scopeLabel(): string
    {
        return app(WorkspaceContext::class)->id() === null
            ? 'على المنصّة كلّها'
            : 'في مساحتك';
    }
}
