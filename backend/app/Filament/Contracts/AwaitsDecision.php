<?php

declare(strict_types=1);

namespace App\Filament\Contracts;

/**
 * شاشةٌ في مجموعةِ «ينتظر قرارك»: طابورٌ يقفُ فيه شيءٌ حتّى يُقرِّرَ إنسان.
 *
 * ⚠️ **العددُ في دالّةٍ واحدة، ويقرؤها العدّادُ والويدجتُ كلاهما.** رقمٌ على
 * القائمةِ ورقمٌ على اللوحةِ يُحسَبانِ في موضعَينِ يفترقانِ عندَ أوّلِ حالةٍ تُضاف،
 * ويقفُ الموظّفُ أمامَ رقمَينِ مختلفَينِ للطابورِ نفسِه.
 *
 * ⚠️ **والعددُ على المنصّةِ كلِّها، متخطّياً نطاقَ المساحة.** كلُّ قارئٍ لهذه
 * الطوابيرِ موظّفُ منصّة، وسياقُه يرتدُّ إلى `users.last_workspace_id` إن كانت له
 * مساحة — فعدٌّ تحتَ النطاقِ يقرأُ «صفر» عن طابورٍ ممتلئ، وهو الطبقةُ الخامسةُ من
 * عيبِ ٠٢٤: بلا خطأ، أسبوعٌ هادئٌ فحسب.
 *
 * ⚠️ **والظهورُ سؤالٌ منفصلٌ عن العدد.** من لا يصلُ الشاشةَ لا يرى رقمَها — لا
 * على القائمةِ ولا على اللوحة — لأنّ رقماً بلا بابٍ يفتحُه خبرٌ عن عملِ غيرِه.
 */
interface AwaitsDecision
{
    /** ما ينتظرُ القرارَ الآن، على المنصّةِ كلِّها. */
    public static function pendingCount(): int;

    /** هل يرى القارئُ الحاليُّ هذا الطابور (عدّاداً وبطاقةً على اللوحة)؟ */
    public static function decisionQueueVisible(): bool;
}
