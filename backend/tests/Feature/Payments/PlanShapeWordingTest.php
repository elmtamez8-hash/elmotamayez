<?php

declare(strict_types=1);

use App\Modules\Payments\Support\PlanShape;

/*
| ٠٣٦ — الباقةُ الواحدةُ لها اسمٌ واحد، على الخادمِ وفي المتصفّح.
|
| ⛔ **وكانَ لها اسمان.** `planDuration()` في `lib/plans.ts` تطوي الثلاثينَ يوماً
| إلى «شهر واحد» منذُ ٠٣٤، وهذا الصنفُ كانَ يقولُ «٣٠ يوماً» — فالمشتري يقرأُ
| اسماً، والموظَّفُ الذي يُسعِّرُ الباقةَ يقرأُ اسماً آخرَ، والإشعارُ الذي يصلُ
| المدرّسَ باسمِه يحملُ الثاني. ومدرّسٌ يفتحُ صفحتَه بعدَ الإشعارِ فيجدُ جملةً
| مختلفةً يظنُّهما باقتَين.
|
| ⚠️ **والجدولُ مكتوبٌ مرّتَينِ عن قصد، هنا وفي `src/lib/plans.test.ts`.** لا
| عقدَ بينَ اللغتَين، فالإملاءُ الواحدُ لا يُفرَضُ إلّا بجدولٍ متطابقٍ على
| الجهتَين — ونسخةٌ واحدةٌ منه في مكانٍ واحدٍ تُثبِتُ أنّ الطرفَ اتّفقَ مع نفسِه.
| **فأيُّ تعديلٍ في أحدِهما يُنقَلُ إلى الآخرِ في الدفعةِ نفسِها.**
|
| ⚠️ **والحالاتُ مُنتقاةٌ على حدودِ البنود، لا على أرقامٍ مريحة.** ١٢ و٣٠ هما
| بالضبطِ البندُ الذي يُوافِقُه القالبُ النصّيُّ صدفةً — فجدولٌ منهما وحدَهما
| أخضرُ فوقَ بناءٍ لا يعرفُ العربيّةَ إطلاقاً.
*/

/** @return list<array{0: int|null, 1: int|null, 2: string|null}> */
function planShapeCases(): array
{
    return [
        // يومٌ بيوم — البنودُ الخمسةُ التي تُغيِّرُ الاسمَ وليسَ الرقمَ وحدَه.
        [1, null, 'يوم واحد'],
        [2, null, 'يومان'],
        [7, null, '٧ أيّام'],
        [11, null, '١١ يوماً'],

        // الطيُّ إلى شهور — وهو نصفُ العطبِ الأصليّ.
        [30, null, 'شهر واحد'],
        [60, null, 'شهران'],
        [90, null, '٣ أشهر'],
        [330, null, '١١ شهراً'],

        // بالحصص.
        [null, 1, 'حصّة واحدة'],
        [null, 2, 'حصّتان'],
        [null, 12, '١٢ حصّة'],

        // ⚠️ صفٌّ نصفُ مكتوبٍ لا يُسمّى «٠ يوماً» — يُسقِطُه القارئُ.
        [null, null, null],
        [0, 0, null],
    ];
}

it('names a plan the same way the buyer’s screen does', function (): void {
    foreach (planShapeCases() as [$days, $sessions, $expected]) {
        expect(PlanShape::describe($days, $sessions))->toBe(
            $expected,
            'المدّة: '.var_export($days, true).' · الحصص: '.var_export($sessions, true),
        );
    }
});

it('prefers the sessions it was sold by over a duration left on the row', function (): void {
    /*
    | ⚠️ الترتيبُ جزءٌ من الجواب: صفٌّ قديمٌ قد يحملُ الاثنَين، و`SavePlan`
    | يرفضُ كتابتَهما معاً اليوم — فالقارئُ يجبُ أن يُسمّيَ واحداً بعينِه بدلَ
    | أن يختلفَ عن أخيه في الواجهةِ بحسبِ أيِّهما نظرَ إليه أوّلاً.
    */
    expect(PlanShape::describe(30, 12))->toBe('١٢ حصّة');
});
