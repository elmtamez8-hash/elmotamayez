<?php

declare(strict_types=1);

use App\Shared\Support\CountedNoun;

/*
| ⛔ **الاسمُ المعدودُ بالعربيّة — خمسُ بِنًى، والبِنيةُ من CLDR لا من سُلَّم.**
|
| كُتِبَ في الواجهةِ أوّلاً بعدَ أن شُحِنَت «٢ مدرّس متاح» إلى السوقِ الحيِّ
| وأُبلِغَ عنها. وهذا نظيرُه في الخادمِ بالقاعدةِ نفسِها ومن البياناتِ نفسِها،
| ليقولَ المُنتقي في اللوحةِ ما تقولُه الشاشةُ للطالب.
|
| ⚠️ **و١٠٣ وَ١١١ هما الاختبارُ كلُّه.** CLDR يحسمُ البِنيةَ بآخرِ رقمَين، فـ١٠٣
| في `few` وَ١١١ في `many` — وسُلَّمٌ مثلُ `n <= 10` يُوافِقُ تحتَ المئةِ ويفترقُ
| فوقَها، حيثُ لا يختبرُ أحد. حالةٌ تقفُ عندَ العشرةِ تمرُّ خضراءَ فوقَ سُلَّمٍ
| مكتوبٍ باليد.
|
| ⚠️ ولا قاعدةَ بياناتٍ هنا: دالّةٌ خالصة.
*/
const SEATS = [
    'one' => 'مقعد واحد متبقٍّ',
    'two' => 'مقعدان متبقّيان',
    'few' => 'مقاعد متبقّية',
    'many' => 'مقعداً متبقّياً',
    'other' => 'مقعد متبقٍّ',
];

it('agrees the noun in every band, including above a hundred', function (int $count, string $expected): void {
    expect(CountedNoun::of($count, SEATS))->toBe($expected);
})->with([
    // الصفرُ جملةٌ، لا «٠ مقعد».
    [0, 'لا مقاعد متبقّية'],
    // الواحدُ والاثنانِ بلا رقم: العربيّةُ تحملُ العددَ في الكلمة.
    [1, 'مقعد واحد متبقٍّ'],
    [2, 'مقعدان متبقّيان'],
    [3, '٣ مقاعد متبقّية'],
    [10, '١٠ مقاعد متبقّية'],
    [11, '١١ مقعداً متبقّياً'],
    [99, '٩٩ مقعداً متبقّياً'],
    // ⚠️ هنا يفترقُ السُّلَّمُ المكتوبُ باليدِ عن CLDR.
    [100, '١٠٠ مقعد متبقٍّ'],
    [103, '١٠٣ مقاعد متبقّية'],
    [111, '١١١ مقعداً متبقّياً'],
]);

it('takes an explicit zero when the caller has a better sentence than «لا»', function (): void {
    /*
    | «لا ساعات» على كورسٍ لم تُقَسْ مدّتُه كذبٌ، و«لا سنوات خبرة» على مدرّسٍ في
    | عامِه الأوّلِ حكمٌ على بطاقةٍ في السوق — فالصفرُ قرارٌ في كلِّ موضع.
    */
    expect(CountedNoun::of(0, [...SEATS, 'zero' => 'اكتملت المجموعة']))
        ->toBe('اكتملت المجموعة');
});

it('writes the numeral in Arabic-Indic digits whatever ICU the image ships', function (): void {
    /*
    | ⛔ **هذا الحارسُ وُلِدَ من عطبٍ قِيسَ على الإنتاجِ بعدَ النشر.**
    |
    | `ar-QA` وحدَها تُعطي `١٠٣` على ICU ٧٧ و`103` على ICU ٧٨ — النسخةُ نفسُها من
    | الكودِ تُعطي شكلَين، لأنّ CLDR غيّرَ نظامَ الأرقامِ الافتراضيَّ لهذه اللغة.
    | فمحلّيّاً ظهرَت الأرقامُ عربيّةً وعلى الإنتاجِ إنجليزيّةً، **بلا سطرٍ في أيِّ
    | فرق** — وأوّلُ بناءٍ يرفعُ ICU كانَ سيقلبُ كلَّ رقمٍ في اللوحةِ صامتاً.
    |
    | فالنظامُ مُثبَّتٌ بـ`-u-nu-arab`، وهذه الحالةُ هي ما يجعلُ ترقيةَ ICU
    | **تُسقِطُ البناء** بدلَ أن تُغيِّرَ المنتَجَ من وراءِ ظهرِ من يقرأُه.
    */
    expect(CountedNoun::of(103, SEATS))->toStartWith('١٠٣')
        ->and(CountedNoun::of(11, SEATS))->toStartWith('١١');
});
