<?php

declare(strict_types=1);

namespace Database\Seeders;

use Illuminate\Database\Seeder;

/**
 * الفهارسُ الخمسةُ التي يقرؤُها التطبيقُ وقتَ التشغيل — مرّةً لكلِّ عمليّةٍ، لا
 * مرّةً لكلِّ اختبار.
 *
 * ⚠️ هذه بياناتٌ مرجعيّةٌ لا تجهيزاتُ حالة. كانت تُبذَرُ في `beforeEach` داخلَ
 * `tests/Pest.php` — ١٨١ استعلاماً × ٢٩١٢ حالةً ≈ ٥٢٧٬٠٠٠ استعلامٍ لصفوفٍ لا
 * تتغيّرُ بينَ اختبارَين. مقيسٌ: ١٠١ مِلّي ثانيةً للحالةِ الواحدة.
 *
 * ⚠️ ونقلُها إلى هنا آمنٌ لسببٍ واحدٍ بعينِه، وهو ترتيبُ خُطّافَين في الإطار:
 * `RefreshDatabase::refreshTestDatabase()` يُهاجرُ ويبذُرُ مرّةً واحدةً
 * (`migrate:fresh --seeder=…`) **ثمَّ** يفتحُ معاملةً لكلِّ اختبارٍ
 * (`beginDatabaseTransaction()`). فالصفوفُ المبذورةُ هنا تسبقُ المعاملة، وأيُّ
 * تعديلٍ يُجريه اختبارٌ عليها — مثلَ `GamificationAction::query()->update(['daily_cap' => null])`
 * في خمسةِ ملفّاتٍ، و`MessageTemplate::query()->updateOrCreate(...)` في
 * `RegistersFakeChannels` — يقعُ داخلَ المعاملةِ ويُلغى معَها. لا تسرُّبَ بينَ
 * اختبارَين، وقد قِيسَ: ٤٠١ اختباراً في تلك الوحداتِ خضراء.
 *
 * ⚠️ والخُطّافُ هو `$seeder` على `Tests\TestCase` لا `afterRefreshingDatabase()`:
 * الثانيةُ تُستدعى **بعدَ** فتحِ المعاملة، فالبذرُ فيها يُلغى مع كلِّ اختبارٍ
 * ويُعادُ في الذي يليه — أي الحالُ نفسُها التي نُغادِرُها، بمظهرِ إصلاح.
 */
class TestCatalogueSeeder extends Seeder
{
    public function run(): void
    {
        /*
         * قوالبُ الرسائل — بياناتٌ مرجعيّةٌ لا تجهيزات.
         *
         * إرسالٌ بلا قالبٍ لنوعِه لا يُصيِّرُ شيئاً ويُسقَطُ مع سطرِ سجلٍّ (FR-037)،
         * فبدونِ هذه يمرُّ كلُّ توكيدٍ عن الإشعاراتِ في الطقمِ **صادقاً على الفراغ**
         * — يطلبُ صفراً فيجدُ صفراً.
         */
        $this->call(NotificationTemplateSeeder::class);

        /*
         * وفهرسُ التلعيب، للسببِ نفسِه تماماً (٠٠٩).
         *
         * ⚠️ `AwardPoints` يبحثُ عن الفعلِ بمفتاحِه ويعودُ صامتاً حينَ لا صفَّ له —
         * فجائزةٌ لفعلٍ غيرِ معرَّفٍ هي فهرسٌ غيرُ مملوءٍ لا خطأ. فبلا صفوفٍ هنا
         * **لا يُمنَحُ شيءٌ أبداً**، وكلُّ توكيدٍ عن النقاطِ والمستوياتِ والسلاسلِ
         * ولوحاتِ الصدارةِ يمرُّ بمقارنةِ صفرٍ بصفر.
         */
        $this->call(GamificationCatalogSeeder::class);

        /*
         * وتصنيفاتُ حمايةِ البيانات، ثالثةً لثالثِ نسخةٍ من الآليّةِ نفسِها (٠١٣).
         *
         * ⚠️ فهرسٌ فارغٌ يجعلُ هذه المرحلةَ كلَّها لا تُوكِّدُ شيئاً: شاشةُ الموافقةِ
         * تسردُ التصنيفات، والكنسُ الليليُّ يمرُّ عليها، واختبارُ تغطيةِ المخطَّطِ
         * يقارنُ بها — وفوقَ صفرِ صفوفٍ ثلاثتُها خضراءُ ولم ينظرْ أيٌّ منها إلى شيء.
         */
        $this->call(DataCategorySeeder::class);

        /*
         * والمناطق (٠١١ · FR-042)، رابعةً — وبفارقٍ يستحقُّ التسمية: هذا الفهرسُ
         * **لا يفشلُ صامتاً**. `region_slug` مطلوبٌ في `RegisterStudentRequest`
         * ومُتحقَّقٌ منه أمامَ هذه الصفوف، فجدولٌ فارغٌ هو ٤٢٢ على كلِّ تسجيلٍ جديدٍ
         * لا لا-فعلٍ صامت.
         */
        $this->call(RegionSeeder::class);

        /*
         * والتصنيفُ الدراسيّ (٠٢٢) — المواد، والمراحلُ العريضة، والسنواتُ الدراسيّة.
         * خامسُ فهرسٍ يُقرَأُ وقتَ التشغيل، وثاني من يرفضُ بدلَ أن يشيحَ:
         * `school_year_slug` مطلوبٌ عندَ التسجيل، وكلا مُنتقيَي الاشتراكِ مُتحقَّقٌ
         * منهما أمامَ هذه الصفوف — فجدولٌ فارغٌ يُغلِقُ البابَ الأماميَّ على الطلّاب
         * **و**معالِجَ التقديمِ على المدرّسين.
         */
        $this->call(TaxonomySeeder::class);
    }
}
