# تغيّرَ تعريفُه، أو خدمةٌ كانت متوقّفة. وحينَ لا يتغيّرُ شيءٌ لا يفعلُ شيئاً — والحاوياتُ
# التي استُبدِلَت أعلاه تعريفُها هو الحاليُّ فلا تُمَسّ.
echo "▸ رفعُ ما بقيَ من الخدمات"
$COMPOSE up -d

