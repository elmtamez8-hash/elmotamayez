#!/usr/bin/env bash
#
# نشرةٌ واحدةٌ على الخادم. يُنادى من `.github/workflows/deploy.yml` عبرَ SSH،
# ويُشغَّلُ باليدِ بالأمرِ نفسِه عندَ الحاجة:
#
#     cd /srv/elmotamayez && ./scripts/deploy.sh
#
# ⚠️ سكربتٌ في المستودعِ لا سلسلةُ أوامرَ في ملفِّ الـworkflow، والسببُ ليس
# ترتيباً: أوامرُ النشرِ المكتوبةُ داخلَ YAML لا يمكنُ تشغيلُها يدويّاً عندَ عطلٍ
# إلّا بنسخِها سطراً سطراً من صفحةِ الويب — وفي تلك اللحظةِ بالذاتِ يُنسى سطر.

set -euo pipefail

COMPOSE="docker compose -f docker/docker-compose.prod.yml --env-file docker/.env"

echo "▸ سحبُ آخرِ ما على main"
git fetch --prune origin
# ⚠️ `reset --hard` لا `pull`. الخادمُ ليس مكانَ تحريرٍ، وتعديلٌ يدويٌّ عليه
# يجعلُ `pull` يفشلُ بتعارضِ دمجٍ في منتصفِ نشرةٍ — أو، أسوأُ، ينجحُ ويُبقي
# التعديلَ حيّاً إلى الأبدِ حيثُ لا يراه أحدٌ في مراجعة.
git reset --hard origin/main

# ⛔ **وهذا السطرُ الذي فوقَه استبدلَ هذا الملفَّ تحتَ أقدامِ bash.**
#
# bash يقرأُ السكربتَ **بإزاحةِ بايتاتٍ** وهو ينفّذُه، لا دفعةً واحدةً إلى
# الذاكرة. و`git reset --hard` يكتبُ نسخةً جديدةً من `deploy.sh` نفسِه في منتصفِ
# ذلكَ القراءة — فكلُّ ما تحتَ هذا السطرِ يُقرَأُ من الملفِّ الجديدِ **من إزاحةِ
# الملفِّ القديم**. فإن اختلفَ طولُ الملفَّينِ قفَزَ التنفيذُ خطواتٍ أو أعادَ
# غيرَها أو وقعَ في منتصفِ كلمة — **بلا خطأٍ واحد، وبنشرةٍ تنتهي خضراء.**
#
# ⚠️ **وقَعَت فِعلاً في ٢٠٢٦-٠٩-١٩**: النشرةُ التي شحنَت حارسَ
# `cohorts:gate-impact` المكتوبَ أسفلَ هذا الملفّ قفَزَت عنه تماماً: سجلُ
# النشرةِ يمضي من «بناءُ الصور» إلى «رفعُ الخدمات» بلا سطرِ الحارسِ ولا
# سطرِ التخطّي، لأنّ النسخةَ التي كانَ bash يقرؤها لم تكن تعرفُ الحارسَ
# أصلاً. وكلُّ تعديلٍ يُكتَبُ لهذا الملفِّ كانَ ينزلُ متأخّراً نشرةً كاملة.
#
# فالعمليّةُ تُستبدَلُ بنفسِها (`exec`) مرّةً واحدةً بعدَ السحب، فيُقرَأُ الملفُّ
# الجديدُ من أوّلِه. والسحبُ والإعادةُ في المرّةِ الثانيةِ بلا أثرٍ: `git reset`
# على ما هو عليه لا يُحرّكُ شيئاً، و`exec` يستبدِلُ العمليّةَ فلا تتراكم.
#
# ⚠️ **وهنا لا في `deploy.yml`.** نقلُ السحبِ إلى الـworkflow يُصلِحُ العطبَ
# ويناقضُ ترويسةَ هذا الملفّ نفسِه: أوامرُ النشرِ داخلَ YAML لا تُشغَّلُ
# يدويّاً وقتَ العطلِ إلّا نسخاً من صفحةِ ويب، وفي تلكَ اللحظةِ بالذاتِ يُنسى سطر.
if [ "${DEPLOY_REEXEC:-0}" != "1" ]; then
    # يُعلِنُ عن نفسِه لأنّ السطرَينِ فوقَه سيظهرانِ مرّتَينِ في السجلّ،
    # وسطرٌ مكرّرٌ بلا تفسيرٍ يُقرَأُ عطباً في نشرة.
    echo "▸ إعادةُ التشغيلِ من نسخةِ السكربتِ الجديدة"
    export DEPLOY_REEXEC=1
    exec bash "$0" "$@"
fi


echo "▸ بناءُ الصور"
$COMPOSE build

# ⛔ **أثرُ بوّابةِ السعرِ يُقاسُ قبلَ التبديل، لا بعدَه (٠٣٦ · FR-010).**
#
# بوّابةُ ٠٣٦ تُخرِجُ من العرضِ كلَّ مجموعةٍ لا يصلُها سعرٌ حيّ. ومجموعةٌ **فيها
# أعضاءٌ بالفعل** تخرجُ من العرضِ تعني غرفةً قائمةً لا يجدُها أحدٌ جديدٌ ولا
# يستطيعُ عضوُها الجديدُ الانضمام. والرقمُ الذي قِيسَ وقتَ كتابةِ المواصفةِ صفرٌ،
# **وهو هشٌّ بالبناء**: المجموعاتُ الحيّةُ ترثُ باقةً واحدةً تغطّي المساحةَ كلَّها،
# فتضييقُ تلك الباقةِ إلى كورسٍ واحدٍ يُسقِطُ الغطاءَ عن مجموعةٍ بلا أن يلمسَها
# أحد. فرقمُ أمسِ ليسَ رقمَ لحظةِ النشر.
#
# ⚠️ **وموضعُه قبلَ `up -d` هو نصفُ فائدتِه.** بعدَه تكونُ الشيفرةُ الجديدةُ
# حيّةً والطلابُ قد فقدوا مجموعتَهم فعلاً، فيصيرُ الأمرُ تقريراً لا حارساً —
# وتعليقُ الصنفِ نفسِه يقولُ ذلكَ بحرفِه. ويُشغَّلُ من **الصورةِ الجديدةِ** في
# حاويةٍ عابرة (`run --rm`)، لأنّ الحاويةَ العاملةَ ما زالت تحملُ الشيفرةَ
# القديمةَ التي قد لا تعرفُ هذا الأمرَ إطلاقاً.
#
# ⚠️ **ولا يكتبُ شيئاً.** حارسٌ يُصلِحُ ما يجدُه يُخفي بالضبطِ ما شُغِّلَ ليُظهِرَه.
#
# ⚠️ **وإن عضَّ فهذه إشارةٌ لا إزعاج**: غرفةٌ فيها طلابٌ ولا باقةَ تصلُها حالٌ
# تستحقُّ قراراً من إنسان. فإن قُرِئَ وقُبِلَ الأثرُ، تُمرَّرُ النشرةُ صراحةً:
#
#     SKIP_COHORT_GATE_CHECK=1 ./scripts/deploy.sh
#
# ومتغيّرٌ يُكتَبُ في سطرِ الأمرِ مرّةً أفضلُ من حارسٍ يُحذَفُ من السكربتِ للأبد.
if [ "${SKIP_COHORT_GATE_CHECK:-0}" = "1" ]; then
    echo "▸ تخطّي فحصِ أثرِ بوّابةِ السعر (بطلبٍ صريح)"
else
    echo "▸ أثرُ بوّابةِ السعرِ قبلَ التبديل"
    $COMPOSE run --rm --no-deps -T -u www-data backend php artisan cohorts:gate-impact
fi

echo "▸ رفعُ الخدمات"
$COMPOSE up -d

# ⛔ **وnginx يُعادُ إنشاؤُه دائماً، وبدونِ ذلك لا يصلُه تعديلُ إعدادٍ أبداً.**
#
# إعدادُه **ملفٌّ مفرَدٌ مركَّب**
# (`./nginx.prod.conf:/etc/nginx/templates/default.conf.template`)، و`git reset
# --hard` أعلاه **يستبدلُ الملفَّ**: يكتبُ ملفّاً جديداً بـinode جديدٍ بدلَ أن
# يعدّلَ القديمَ في مكانِه. وتركيبُ ملفٍّ مفرَدٍ يمسكُ الـinode لا الاسمَ، فالحاويةُ
# تظلُّ ترى النسخةَ القديمةَ ما دامت تعمل. و`up -d` لا يُعيدُ إنشاءَها: **تعريفُ**
# الخدمةِ لم يتغيّر، ومحتوى ملفٍّ مركَّبٍ ليس جزءاً من التعريف.
#
# ولا يكفي `nginx -s reload` ولا إعادةُ تشغيلِ سكربتِ القالبِ من الداخل: كلاهما
# يقرأُ الـinode القديمَ نفسَه — جُرِّبَ الاثنانِ على الإنتاجِ في ٢٠٢٦-٠٩-١٧
# وأجابا «تمّ» وغيّرا لا شيء.
#
# قِيسَ يومَها: `/panel/enter/{ticket}` أجابَ ٤٠٤ بعدَ نشرةٍ **ناجحة** تحملُ
# `location ^~ /panel` في المستودعِ وعلى قرصِ الخادمِ معاً — نصفُ جسرٍ مشحونٍ لا
# يعبرُه أحد. و`RouteReachabilityTest` يحرسُ وجودَ السطرِ في الملفّ؛ وهذا السطرُ
# يحرسُ وصولَ الملفِّ إلى nginx. سؤالان مختلفان.
#
# والثمنُ جزءٌ من ثانية: nginx يُقلِعُ فوراً، ونقطةُ الدخولِ تُعيدُ توليدَ القالبِ
# من تلقائِها.
echo "▸ إعادةُ إنشاءِ nginx (إعدادُه ملفٌّ مركَّبٌ يستبدلُه git)"
$COMPOSE up -d --force-recreate nginx

echo "▸ انتظارُ قاعدةِ البيانات"
# الفحصُ الصحّيُّ في ملفِّ الـcompose يحرسُ الإقلاع؛ هذا يحرسُ الهجرةَ بعدَ
# إعادةِ بناءٍ قد تكون أعادت تشغيلَ MySQL للتوّ.
until $COMPOSE exec -T mysql mysqladmin ping --silent 2>/dev/null; do sleep 2; done

echo "▸ الهجرات"
# ⚠️ `--force` لأنّ الأمرَ يسألُ تأكيداً في بيئةِ الإنتاجِ ولا أحدَ هنا ليُجيب،
# فيتعلّقُ إلى أن تنتهيَ مهلةُ الوظيفة. و**لا `migrate:fresh` أبداً**: تلك تُسقِطُ
# كلَّ جدولٍ — كلَّ طالبٍ وكلَّ دفعةٍ وكلَّ تسجيل.
$COMPOSE exec -T -u www-data backend php artisan migrate --force

echo "▸ إعادةُ بناءِ ذاكرةِ الإعدادات"
# ⚠️ بهذا الترتيب: `config:clear` قبلَ `config:cache`. ملفُّ ذاكرةٍ قديمٌ يحملُ
# قيمَ `.env` السابقةَ ويتجاهلُ الجديدةَ بصمت — فتُقرأُ نشرةٌ صحيحةٌ على أنّها
# إعدادٌ خاطئ.
# ⚠️ `-u www-data`، وهو ما كان ناقصاً. `docker compose exec` يعملُ بصلاحيّةِ
# **root**، و`view:cache` يكتبُ كلَّ قالبٍ مُصرَّفٍ مملوكاً لـroot — بينما حوضُ
# PHP-FPM يعملُ بـ`www-data`. وBlade يستدعي `touch()` ليُطابِقَ زمنَ الملفِّ
# المُصرَّفِ بالمصدر، و`utime()` لا يُسمَحُ بها إلّا لمالكِ الملفّ:
#
#     touch(): Utime failed: Operation not permitted   (BladeCompiler.php:215)
#
# فتردُّ **٥٠٠ كلُّ صفحةِ Blade** — `/admin/login` أوّلُها. ولا يظهرُ في فحصٍ
# دخانيّ: `/` تخدمُها Next، و`/admin` تُحوِّلُ ٣٠٢ قبلَ تصييرِ أيِّ قالب.
$COMPOSE exec -T -u www-data backend php artisan config:clear
$COMPOSE exec -T -u www-data backend php artisan config:cache
$COMPOSE exec -T -u www-data backend php artisan route:cache
$COMPOSE exec -T -u www-data backend php artisan view:cache

# وشبكةُ أمانٍ فوقَها: أيُّ `artisan` يُشغَّلُ يدويّاً بعدَ نشرةٍ (بذرٌ، `tinker`،
# تشخيص) يعملُ بـroot ويُعيدُ التلويثَ نفسَه. سطرٌ واحدٌ يُنظِّفُ الصنفَ كلَّه.
$COMPOSE exec -T backend chown -R www-data:www-data storage bootstrap/cache

# ⚠️ ولا بذرةَ هنا، ولا حتى «للاحتياط». الفهارسُ التي تُقرَأُ وقتَ التشغيلِ
# (قوالبُ الإشعاراتِ · فئاتُ البيانات · فهرسُ التلعيب) تُردَمُ بهجرةٍ تُشحَنُ مع
# الصفِّ الذي يحتاجُها — وهي قاعدةٌ مكتوبةٌ في `CLAUDE.md` لأنّها كُسِرَت ثلاثَ
# مرّات. وبذرةٌ في مسارِ النشرِ تكتبُ `updateOrCreate`، أي أنّها **تدهسُ كلَّ نصٍّ
# عربيٍّ وكلَّ مدّةٍ عدّلها مشغِّلٌ من `/admin`، في كلِّ نشرة**. البذورُ الأولى
# (الأدوارُ والصلاحيّاتُ وإعداداتُ المنصّة) تُشغَّلُ مرّةً واحدةً عندَ أوّلِ إقلاع،
# وهي موصوفةٌ في `docs/deploy-hostinger.md`.

echo "▸ إعادةُ تشغيلِ العامل"
# ⚠️ `queue:restart` لا إعادةَ تشغيلِ الحاوية. العاملُ يُمسِكُ الشيفرةَ التي أقلعَ
# بها، فيظلُّ يفشلُ بخطأٍ أزالَه الـcommit — ساعتان ضاعتا مرّةً على أثرِ استدعاءٍ
# لم يعدْ موجوداً في أيِّ ملفّ.
$COMPOSE exec -T -u www-data backend php artisan queue:restart
$COMPOSE restart horizon scheduler reverb

echo "▸ تنظيفُ الصورِ القديمة"
docker image prune -f >/dev/null

echo "▸ جدولةُ النسخةِ الاحتياطيّة"
# ⚠️ كانت سطراً في تعليقٍ أسفلَ `backup.sh` يُنصَّبُ باليد — أي لا يضمنُ أحدٌ
# أنّه نُصِّب. هنا يُضافُ إن غاب ولا يتكرّر إن وُجِد، فكلُّ نشرةٍ تؤكّدُه.
BACKUP_CRON='17 3 * * * cd /srv/elmotamayez && bash scripts/backup.sh >> /var/log/elmotamayez-backup.log 2>&1'
crontab -l 2>/dev/null | grep -qF 'scripts/backup.sh' \
    || { (crontab -l 2>/dev/null; echo "$BACKUP_CRON") | crontab - && echo "  + أُضيفَت"; } \
    || echo "  ✗ تعذّرت الجدولة — النسخُ الاحتياطيّةُ لا تعمل" >&2

echo "▸ فحصٌ دخانيّ"
# ⚠️ **صفحةُ Blade واحدةٌ على الأقلّ، وهذا هو بيتُ القصيد.** كانت قائمةُ الفحصِ
# كلُّها خضراءَ بينما `/admin/login` ترُدُّ ٥٠٠: `/` تخدمُها Next، و`/admin`
# تُحوِّلُ ٣٠٢ **قبلَ** تصييرِ أيِّ قالب، و`/api` تُعيدُ JSON بلا Blade. فلا نقطةَ
# واحدةً في القائمةِ كانت تُصرِّفُ قالباً — والشاشةُ الوحيدةُ التي يفتحُها إنسانٌ
# ليدخلَ هي بالضبط الشاشةُ التي لم يفحصْها شيء.
DOMAIN_NAME=$(sed -n 's/^DOMAIN=//p' docker/.env | head -1)
FAILED=0
for path in "/" "/api/v1/marketplace/home" "/admin/login"; do
    code=$(curl -s -o /dev/null -w "%{http_code}" -m 30 "https://${DOMAIN_NAME}${path}" || echo 000)
    case "$code" in
        2*|3*) printf '  ✓ %-28s %s
' "$path" "$code" ;;
        *)     printf '  ✗ %-28s %s
' "$path" "$code"; FAILED=1 ;;
    esac
done
[ "$FAILED" -eq 0 ] || { echo "✗ النشرةُ تمّت والموقعُ لا يردّ — راجعْ فوراً." >&2; exit 1; }

echo "✓ تمّت النشرة: $(git rev-parse --short HEAD)"
