echo "▸ جدولةُ إعادةِ تحميلِ شهادةِ nginx"
# ⚠️ النشرةُ لم تعدْ تُعيدُ إنشاءَ nginx إلّا حينَ يتغيّرُ ملفُّه، والـ`reload` أعلاه
# لا يجري إلّا مع نشرة. فشهرٌ بلا نشرةٍ يتركُ شهادةً جدَّدها certbot على القرصِ
# ولم يُحمِّلْها nginx، حتى تنتهيَ القديمة. سطرٌ أسبوعيٌّ يُغلِقُ ذلك، بالطريقةِ نفسِها.
RELOAD_CRON='41 4 * * 1 cd /srv/elmotamayez && docker compose -f docker/docker-compose.prod.yml --env-file docker/.env exec -T nginx nginx -s reload >> /var/log/elmotamayez-nginx-reload.log 2>&1'
crontab -l 2>/dev/null | grep -qF 'nginx -s reload' \
    || { (crontab -l 2>/dev/null; echo "$RELOAD_CRON") | crontab - && echo "  + أُضيفَت"; } \
