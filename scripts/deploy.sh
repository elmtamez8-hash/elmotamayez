#!/usr/bin/env bash
#
# نشرةٌ واحدةٌ على الخادم. يُنادى من `.github/workflows/deploy.yml` عبرَ SSH،
# ويُشغَّلُ باليدِ بالأمرِ نفسِه عندَ الحاجة:
#
#     cd /srv/elmotamayez && ./scripts/deploy.sh
#
# ⚠️ سكربتٌ في المستودعِ لا سلسلةُ أوامرَ في ملفِّ الـworkflow، والسببُ ليس
# ترتيباً: أوامرُ النشرِ المكتوبةُ داخلَ YAML لا يمكنُ تشغيلُها يدويّاً عندَ عطلٍ
# إلّا بنسخِها سطراً سطراً من صفحةِ الويب — وفي تلك اللحظةِ بالذاتِ يُنسى سطر.

set -euo pipefail

COMPOSE="docker compose -f docker/docker-compose.prod.yml --env-file docker/.env"

echo "▸ سحبُ آخرِ ما على main"
git fetch --prune origin
# ⚠️ `reset --hard` لا `pull`. الخادمُ ليس مكانَ تحريرٍ، وتعديلٌ يدويٌّ عليه
# يجعلُ `pull` يفشلُ بتعارضِ دمجٍ في منتصفِ نشرةٍ — أو، أسوأُ، ينجحُ ويُبقي
# التعديلَ حيّاً إلى الأبدِ حيثُ لا يراه أحدٌ في مراجعة.
git reset --hard origin/main

# ⛔ **وهذا السطرُ الذي فوقَه استبدلَ هذا الملفَّ تحتَ أقدامِ bash.**
#
# bash يقرأُ السكربتَ **بإزاحةِ بايتاتٍ** وهو ينفّذُه، لا دفعةً واحدةً إلى
# الذاكرة. و`git reset --hard` يكتبُ نسخةً جديدةً من `deploy.sh` نفسِه في منتصفِ
# ذلكَ القراءة — فكلُّ ما تحتَ هذا السطرِ يُقرَأُ من الملفِّ الجديدِ **من إزاحةِ
# الملفِّ القديم**. فإن اختلفَ طولُ الملفَّينِ قفَزَ التنفيذُ خطواتٍ أو أعادَ
# غيرَها أو وقعَ في منتصفِ كلمة — **بلا خطأٍ واحد، وبنشرةٍ تنتهي خضراء.**
#
# ⚠️ **وقَعَت فِعلاً في ٢٠٢٦-٠٩-١٩**: النشرةُ التي شحنَت حارسَ
# `cohorts:gate-impact` المكتوبَ أسفلَ هذا الملفّ قفَزَت عنه تماماً: سجلُ
# النشرةِ يمضي من «بناءُ الصور» إلى «رفعُ الخدمات» بلا سطرِ الحارسِ ولا
# سطرِ التخطّي، لأنّ النسخةَ التي كانَ bash يقرؤها لم تكن تعرفُ الحارسَ
# أصلاً. وكلُّ تعديلٍ يُكتَبُ لهذا الملفِّ كانَ ينزلُ متأخّراً نشرةً كاملة.
#
# فالعمليّةُ تُستبدَلُ بنفسِها (`exec`) مرّةً واحدةً بعدَ السحب، فيُقرَأُ الملفُّ
# الجديدُ من أوّلِه. والسحبُ والإعادةُ في المرّةِ الثانيةِ بلا أثرٍ: `git reset`
# على ما هو عليه لا يُحرّكُ شيئاً، و`exec` يستبدِلُ العمليّةَ فلا تتراكم.
#
# ⚠️ **وهنا لا في `deploy.yml`.** نقلُ السحبِ إلى الـworkflow يُصلِحُ العطبَ
# ويناقضُ ترويسةَ هذا الملفّ نفسِه: أوامرُ النشرِ داخلَ YAML لا تُشغَّلُ
# يدويّاً وقتَ العطلِ إلّا نسخاً من صفحةِ ويب، وفي تلكَ اللحظةِ بالذاتِ يُنسى سطر.
if [ "${DEPLOY_REEXEC:-0}" != "1" ]; then
    # يُعلِنُ عن نفسِه لأنّ السطرَينِ فوقَه سيظهرانِ مرّتَينِ في السجلّ،
    # وسطرٌ مكرّرٌ بلا تفسيرٍ يُقرَأُ عطباً في نشرة.
    echo "▸ إعادةُ التشغيلِ من نسخةِ السكربتِ الجديدة"
    export DEPLOY_REEXEC=1
    exec bash "$0" "$@"
fi


echo "▸ بناءُ الصور"
$COMPOSE build

# ⛔ **أثرُ بوّابةِ السعرِ يُقاسُ قبلَ التبديل، لا بعدَه (٠٣٦ · FR-010).**
#
# بوّابةُ ٠٣٦ تُخرِجُ من العرضِ كلَّ مجموعةٍ لا يصلُها سعرٌ حيّ. ومجموعةٌ **فيها
# أعضاءٌ بالفعل** تخرجُ من العرضِ تعني غرفةً قائمةً لا يجدُها أحدٌ جديدٌ ولا
# يستطيعُ عضوُها الجديدُ الانضمام. والرقمُ الذي قِيسَ وقتَ كتابةِ المواصفةِ صفرٌ،
# **وهو هشٌّ بالبناء**: المجموعاتُ الحيّةُ ترثُ باقةً واحدةً تغطّي المساحةَ كلَّها،
# فتضييقُ تلك الباقةِ إلى كورسٍ واحدٍ يُسقِطُ الغطاءَ عن مجموعةٍ بلا أن يلمسَها
# أحد. فرقمُ أمسِ ليسَ رقمَ لحظةِ النشر.
#
# ⚠️ **وموضعُه قبلَ `up -d` هو نصفُ فائدتِه.** بعدَه تكونُ الشيفرةُ الجديدةُ
# حيّةً والطلابُ قد فقدوا مجموعتَهم فعلاً، فيصيرُ الأمرُ تقريراً لا حارساً —
# وتعليقُ الصنفِ نفسِه يقولُ ذلكَ بحرفِه. ويُشغَّلُ من **الصورةِ الجديدةِ** في
# حاويةٍ عابرة (`run --rm`)، لأنّ الحاويةَ العاملةَ ما زالت تحملُ الشيفرةَ
# القديمةَ التي قد لا تعرفُ هذا الأمرَ إطلاقاً.
#
# ⚠️ **ولا يكتبُ شيئاً.** حارسٌ يُصلِحُ ما يجدُه يُخفي بالضبطِ ما شُغِّلَ ليُظهِرَه.
#
# ⚠️ **وإن عضَّ فهذه إشارةٌ لا إزعاج**: غرفةٌ فيها طلابٌ ولا باقةَ تصلُها حالٌ
# تستحقُّ قراراً من إنسان. فإن قُرِئَ وقُبِلَ الأثرُ، تُمرَّرُ النشرةُ صراحةً:
#
#     SKIP_COHORT_GATE_CHECK=1 ./scripts/deploy.sh
#
# ومتغيّرٌ يُكتَبُ في سطرِ الأمرِ مرّةً أفضلُ من حارسٍ يُحذَفُ من السكربتِ للأبد.
if [ "${SKIP_COHORT_GATE_CHECK:-0}" = "1" ]; then
    echo "▸ تخطّي فحصِ أثرِ بوّابةِ السعر (بطلبٍ صريح)"
else
    echo "▸ أثرُ بوّابةِ السعرِ قبلَ التبديل"
    $COMPOSE run --rm --no-deps -T -u www-data backend php artisan cohorts:gate-impact
fi

# ⛔ **حزمُ الواجهةِ تُؤرشَفُ قبلَ التبديل، وإلّا انكسرَت كلُّ تبويبةٍ مفتوحة.**
#
# صورةُ Next لا تحملُ إلّا `.next/static` بنائِها هي. فصفحةٌ حُمِّلَت قبلَ النشرةِ
# تطلبُ بعدَها حزمةً باسمِ البناءِ القديم (`chunks/5613-0374f….js`) لم تعدْ في أيِّ
# حاوية ← ٤٠٤، وحينَ تكونُ حزمةَ التخطيطِ الجذريِّ لا يصلُ حتى حدُّ الخطأ.
# فالمجلّدُ المُسمّى `next-static` يجمعُ حزمَ البناءِ **القائمِ** (من الحاويةِ العاملةِ
# نفسِها، لا من وسمِ الصورة: نشرةٌ سابقةٌ فشلَت بعدَ البناءِ تُبقي الوسمَ على صورةٍ
# لم تخدمْ أحداً) و**الجديد**، وnginx يخدمُه مباشرةً.
#
# ⚠️ `tar -m` لا يستعيدُ زمنَ الملفّ: كلُّ ما يُنسَخُ الآنَ زمنُه **الآن**، فالحذفُ
# بعدَ يومَينِ يقيسُ «منذُ آخرِ نشرةٍ كانَ فيها هذا الملفُّ حيّاً» لا «منذُ بُنِي» —
# وإلّا حُذِفَت حزمُ بناءٍ لم يتغيّرْ مصدرُه (طبقةٌ مخزَّنةٌ عمرُها أسبوع) لحظةَ نسخِها.
#
# ⚠️ **وفشلُه لا يُفشِلُ النشرة**: nginx يعودُ إلى Next لكلِّ ملفٍّ غائب، فأسوأُ
# ما يحدثُ هو ما كانَ يحدثُ قبلَ اليوم. سطرُ تحذيرٍ ظاهرٌ خيرٌ من موقعٍ لم يُنشَر.
echo "▸ أرشفةُ حزمِ الواجهة (القائمةِ والجديدة) قبلَ التبديل"
archive_next_static() {
    $COMPOSE run --rm --no-deps -T next-static-archive \
        'tar -xmf - -C /archive && chmod -R a+rX /archive'
}
if [ -n "$($COMPOSE ps -q frontend)" ]; then
    $COMPOSE exec -T frontend tar -C /app/.next/static -cf - . | archive_next_static \
        || echo "  ✗ تعذّرت أرشفةُ حزمِ البناءِ القائم — التبويباتُ المفتوحةُ قد تنكسر" >&2
fi
docker run --rm --entrypoint tar elmotamayez-frontend:latest -C /app/.next/static -cf - . | archive_next_static \
    || echo "  ✗ تعذّرت أرشفةُ حزمِ البناءِ الجديد — ستُخدَمُ من Next مباشرةً" >&2
$COMPOSE run --rm --no-deps -T next-static-archive \
    'find /archive -type f -mmin +2880 -delete; find /archive -mindepth 1 -type d -empty -delete' \
    || echo "  ✗ تعذّرَ تنظيفُ الأرشيف" >&2

echo "▸ انتظارُ قاعدةِ البيانات"
# الفحصُ الصحّيُّ في ملفِّ الـcompose يحرسُ الإقلاع؛ هذا يحرسُ الهجرةَ التي تليه.
# ⚠️ `up -d` لهما أوّلاً لأنّ هذا صارَ **قبلَ** أيِّ `up`: على قاعدةٍ متوقّفةٍ كانت
# الحلقةُ تدورُ إلى أن تنقضيَ مهلةُ Actions (ستُّ ساعات). وهو لا يفعلُ شيئاً حينَ
# تعملانِ بتعريفِهما الحاليّ. والحلقةُ محدودةٌ بدقيقتَين، فالعطلُ يُسمّي نفسَه.
$COMPOSE up -d mysql redis
DB_WAIT=0
until $COMPOSE exec -T mysql mysqladmin ping --silent 2>/dev/null; do
    DB_WAIT=$((DB_WAIT + 1))
    [ "$DB_WAIT" -lt 60 ] || { echo "✗ قاعدةُ البياناتِ لم تُجِبْ خلالَ دقيقتَين — لم يُبدَّلْ شيء." >&2; exit 1; }
    sleep 2
done

# ⛔ **الهجراتُ من الصورةِ الجديدةِ قبلَ التبديل، لا بعدَه.**
#
# كانت تُشغَّلُ بعدَ `up -d`، أي أنّ الشيفرةَ الجديدةَ كانت تخدمُ الزوّارَ دقيقةً على
# مخطّطٍ قديم: عمودٌ جديدٌ يقرؤه كلُّ طلبٍ يردُّ ٥٠٠ حتى تنتهيَ الهجرة. قاعدةُ هذا
# المستودعِ أنّ الهجرةَ **إضافيّة** (عمودٌ يُضاف، جدولٌ يُنشأ، صفٌّ يُردَم)، فالشيفرةُ
# القديمةُ لا ترى الجديدَ ولا تتضرّرُ منه — فالترتيبُ الآمنُ هو الهجرةُ أوّلاً.
#
# ⚠️ **والحذفُ وإعادةُ التسميةِ تُقسَمانِ على نشرتَين**: هجرةٌ تُسقِطُ أو تُعيدُ تسميةَ
# عمودٍ ما زالت الشيفرةُ القائمةُ تقرؤه تكسرُها في الدقيقةِ بينَ هذا السطرِ والتبديل
# (مواصفةُ ٠٥٥ أعادت تسميةَ أربعةَ عشرَ عموداً دفعةً واحدة). فالشيفرةُ تكفُّ عن الاسمِ
# القديمِ في نشرة، والعمودُ يُسقَطُ في التالية — والترتيبُ القديمُ كانَ يحملُ الخطرَ
# المعاكسَ نفسَه: شيفرةٌ جديدةٌ دقيقةً كاملةً على مخطّطٍ لم يُهاجَرْ بعد.
#
# `run --rm` من الصورةِ الجديدة، كما حارسُ البوّابةِ أعلاه: الحاويةُ العاملةُ ما زالت
# تحملُ الشيفرةَ القديمةَ التي لا تعرفُ هجراتِ هذه النشرة. و`--force` لأنّ الأمرَ
# يسألُ تأكيداً في الإنتاجِ ولا أحدَ هنا ليُجيب. و**لا `migrate:fresh` أبداً**.
echo "▸ الهجراتُ من الصورةِ الجديدةِ قبلَ التبديل"
$COMPOSE run --rm --no-deps -T -u www-data backend php artisan migrate --force

# ⚠️ ملكيّةُ مجلّدِ المرفوعاتِ **قبلَ** رفعِ الخدمات، لا بعدَه فقط. `horizon`
# و`scheduler` و`reverb` صاروا يعملونَ بـwww-data (انظر `docker-compose.prod.yml`)،
# وكانوا root — فكلُّ ما كتبوه على مجلّدِ `storage` منذُ آخرِ نشرةٍ ملكُ root،
# ونبضةُ المجدوِلِ منه. و`up -d` أدناه يُعيدُ إنشاءَهم فوراً بالمستخدمِ الجديد،
# بينما `chown` الموجودُ أسفلَ الملفِّ يأتي بعدَ الهجراتِ بدقيقة: نافذةٌ يفشلُ فيها
# لمسُ النبضةِ وكتابةُ المهامِّ في مجلّداتٍ ملكِ root.
#
# و`find ! -user` لا `chown -R`: يمسُّ ما ليسَ لـwww-data وحدَه، فيكونُ في كلِّ
# نشرةٍ بعدَ الأولى مروراً للقراءةِ بلا كتابة — ويبقى آمناً إن أُعيدَ مئةَ مرّة.
# و`-h` كي لا يتبعَ رابطاً رمزيّاً إلى خارجِ المجلّد.
echo "▸ ملكيّةُ المرفوعاتِ لـwww-data"
$COMPOSE run --rm --no-deps -T -u root backend \
    find storage/app storage/logs ! -user www-data -exec chown -h www-data:www-data {} +

# ⛔ **وnginx يُعادُ إنشاؤُه حينَ يتغيّرُ ملفُّه — وحينَها فقط.**
#
# إعدادُه **ملفٌّ مفرَدٌ مركَّب**
# (`./nginx.prod.conf:/etc/nginx/templates/default.conf.template`)، و`git reset
# --hard` أعلاه **يستبدلُ الملفَّ**: يكتبُ ملفّاً جديداً بـinode جديدٍ بدلَ أن
# يعدّلَ القديمَ في مكانِه. وتركيبُ ملفٍّ مفرَدٍ يمسكُ الـinode لا الاسمَ، فالحاويةُ
# تظلُّ ترى النسخةَ القديمةَ ما دامت تعمل. و`up -d` لا يُعيدُ إنشاءَها: **تعريفُ**
# الخدمةِ لم يتغيّر، ومحتوى ملفٍّ مركَّبٍ ليس جزءاً من التعريف.
#
# ولا يكفي `nginx -s reload` ولا إعادةُ تشغيلِ سكربتِ القالبِ من الداخل: كلاهما
# يقرأُ الـinode القديمَ نفسَه — جُرِّبَ الاثنانِ على الإنتاجِ في ٢٠٢٦-٠٩-١٧
# وأجابا «تمّ» وغيّرا لا شيء.
#
# قِيسَ يومَها: `/panel/enter/{ticket}` أجابَ ٤٠٤ بعدَ نشرةٍ **ناجحة** تحملُ
# `location ^~ /panel` في المستودعِ وعلى قرصِ الخادمِ معاً — نصفُ جسرٍ مشحونٍ لا
# يعبرُه أحد. و`RouteReachabilityTest` يحرسُ وجودَ السطرِ في الملفّ؛ وهذا السطرُ
# يحرسُ وصولَ الملفِّ إلى nginx. سؤالان مختلفان.
#
# ⚠️ **لكنّ إعادةَ إنشائِه في كلِّ نشرةٍ كانت تقطعُ كلَّ شيء**: كلَّ طلبٍ في منتصفِه،
# وكلَّ سوكِتٍ مفتوح (Reverb يمرُّ من هنا)، ونبضاتِ الحضورِ في حصّةٍ حيّة — نحوَ
# ثانية، في كلِّ نشرة، ولو لم يتغيّرْ في إعدادِه حرف. فبصمةُ الملفِّ تُحفَظُ على
# الخادمِ بجانبِ `.env` (غيرُ متتبَّعةٍ، فـ`git reset --hard` لا يمسُّها)، ويُعادُ
# الإنشاءُ حينَ تختلفُ وحدَها. غيابُ الملفِّ (أوّلُ نشرةٍ بهذه النسخة) يُعَدُّ تغيّراً.
#
# ولا حاجةَ إلى `reload` حينَ لا يتغيّرُ الملفّ: حاوياتُ الخلفيّةِ والواجهةِ الجديدةُ
# تصلُها من DNS دوكر بلا لمسِ nginx (انظر الاستبدالَ أدناه).
#
# ⚠️ **وموضعُه قبلَ الاستبدالِ لا بعدَه**: nginx الجديدُ هو الذي يخدمُ أرشيفَ الحزمِ
# أعلاه، فإن جاءَ بعدَ تبديلِ الواجهةِ انكسرَت التبويباتُ المفتوحةُ ثوانيَ بينَهما.
#
# ⚠️ **وتعريفُ الخدمةِ نفسُه** (مجلّدٌ مركَّب، صورة، منفذ) ليسَ من شأنِ البصمة:
# `up -d` العامُّ أدناه يرى تغيّرَ التعريفِ ويُعيدُ الإنشاءَ وحدَه، كما فعلَ دائماً.
NGINX_CONF_HASH_FILE=docker/.nginx.prod.conf.sha256
NGINX_CONF_HASH=$(sha256sum docker/nginx.prod.conf | cut -d' ' -f1)
if [ "$(cat "$NGINX_CONF_HASH_FILE" 2>/dev/null || true)" != "$NGINX_CONF_HASH" ]; then
    echo "▸ إعادةُ إنشاءِ nginx (تغيّرَ ملفُّ إعدادِه)"
    $COMPOSE up -d --no-deps --force-recreate nginx
    echo "$NGINX_CONF_HASH" > "$NGINX_CONF_HASH_FILE"
else
    # ⛔ **`reload` هنا ليسَ للإعداد — هو للشهادة.** `certbot` يُجدِّدُ الشهادةَ في
    # مجلّدِ `certbot-conf`، وnginx يُمسِكُ ما قرأه عندَ إقلاعِه حتى يُعادَ تحميلُه.
    # إعادةُ الإنشاءِ في كلِّ نشرةٍ كانت تُخفي ذلك؛ وبدونِها يعملُ nginx أسابيعَ بشهادةٍ
    # جُدِّدَت على القرصِ ولم تُحمَّل، فيسقطُ الموقعُ يومَ انتهائِها بسجلِّ نشرٍ أخضر.
    # و`reload` رشيقٌ لا يقطعُ اتّصالاً، وقيدُ الـinode المكتوبُ أعلاه لا يمسُّه: الشهاداتُ
    # **مجلّدٌ** مركَّب لا ملفٌّ مفرَد، والقالبُ القديمُ هو نفسُه ما يعملُ الآنَ على أيِّ حال.
    echo "▸ nginx باقٍ كما هو (ملفُّ إعدادِه لم يتغيّر) — إعادةُ تحميلٍ للشهادةِ فقط"
    $COMPOSE exec -T nginx nginx -s reload \
        || echo "  ✗ تعذّرت إعادةُ تحميلِ nginx — الشهادةُ المُجدَّدةُ قد لا تُحمَّل" >&2
fi

# ⛔ **استبدالٌ بلا فجوة: الجديدةُ تُقلِعُ بجانبِ القديمةِ ثمّ تُطفَأُ القديمة.**
#
# `up -d` على خدمةٍ بنسخةٍ واحدةٍ **يُوقِفُ القديمةَ ثمّ يُنشئُ الجديدة**، و`--wait`
# لا يُغيّرُ الترتيبَ بل ينتظرُ بعدَه. فكلُّ نشرةٍ كانت ثوانيَ من ٥٠٢ للواجهةِ ثمّ
# للخلفيّة — ثانيةً على الأقلّ وعشراً حينَ يتأخّرُ الإقلاع. والبديلُ:
#
#   ١. `--scale svc=2 --no-recreate`: حاويةٌ ثانيةٌ من الصورةِ الجديدةِ **بجانبِ**
#      القديمة، التي لا تُمَسّ.
#   ٢. ننتظرُ فحصَها الصحّيَّ (المكتوبَ في الـcompose — مصدرٌ واحد) حتى `healthy`.
#      إن اعتلَّت أو ماتت تُزالُ **هي** وتفشلُ النشرةُ والقديمةُ ما زالت تخدم:
#      صورةٌ مكسورةٌ لا تُسقِطُ الموقع.
#   ٣. ننتظرُ ١٢ ثانية، ثمّ نُطفئُ القديمة.
#
# ⚠️ **ولماذا تعملُ الخطوةُ الثالثةُ بلا لمسِ nginx**: كلُّ `proxy_pass`/`fastcgi_pass`
# في `nginx.prod.conf` يمرُّ بمتغيّر (`set $php_upstream backend:9000`) مع
# `resolver 127.0.0.11 valid=10s`، فnginx يسألُ DNS دوكر عن الاسمِ كلَّ عشرِ ثوانٍ
# ولا يحفظُ عنوانَ حاويةٍ بعينِها. والاسمُ يُجيبُ بعنوانَي النسختَينِ معاً، فالـ١٢ ثانيةً
# تضمنُ أنّ nginx رأى الجديدةَ قبلَ أن تغيبَ القديمة؛ وفي الثواني العشرِ بعدَ إطفائِها
# قد يختارُ عنوانَها الغائب، فتنقضي مهلةُ الاتّصالِ (٣ ثوانٍ، `*_connect_timeout` في
# `nginx.prod.conf` — الافتراضيُّ ٦٠) ويُعيدُ المحاولةَ على الأخرى (`*_next_upstream`
# الافتراضيّ `error timeout`). وإعادةُ المحاولةِ مسموحةٌ حتى لـPOST لأنّ الطلبَ لم يُرسَلْ.
# قِيسَ على نموذجٍ محلّيٍّ بهذه الدالّةِ نفسِها وطلبٍ كلَّ ٥٠ms: صفرُ طلباتٍ فاشلة
# (وطلبٌ أو اثنانِ تأخّرا حتى ثلاثِ ثوانٍ)، مقابلَ ستّةٍ أو سبعةٍ فاشلةٍ بـ`up -d` العاديّ.
#
# ⚠️ **والثمنُ المقبول**: طلبٌ **في منتصفِه** على القديمةِ لحظةَ إطفائِها. FPM يُطفَأُ
# بـSIGQUIT (إشارةُ صورتِه) فيُنهي ما بدأه؛ وNode قد يقطعُه. رفعُ ملفٍّ طويلٍ على
# القديمةِ في تلك اللحظةِ بعينِها يُعادُ من المستخدم.
#
# ⚠️ **ولا يُطبَّقُ إلّا على `backend` و`frontend`**: بلا حالةٍ وخلفَ nginx. نسختانِ
# من `scheduler` تُنفِّذانِ كلَّ مهمّةٍ مجدولةٍ مرّتَين، و`reverb` يحملُ اتّصالاتٍ
# مفتوحة، و`horizon` لا يخدمُ طلباً فلا فجوةَ فيه يراها أحد.
#
# ⚠️ **والرقمُ بعدَ الشَّرطةِ يتغيّر** (`backend-1` ← `-2` ← `-3`)، وهذا مقيسٌ لا
# مفترَض: `compose exec`/`ps`/`up -d` بعدَها تتعاملُ مع الحاويةِ الوحيدةِ أيّاً كانَ رقمُها،
# و`up -d` العامُّ لا يُعيدُ إنشاءَها لأنّ تعريفَها هو التعريفُ الحاليّ.
roll_service() {
    local svc=$1 old new status count waited=0
    old=$($COMPOSE ps -a -q "$svc")
    if [ -z "$old" ]; then
        # أوّلُ إقلاعٍ على هذا الخادم: لا قديمةَ تُستبدَل.
        $COMPOSE up -d --no-deps "$svc"
        return
    fi
    count=$(printf '%s\n' "$old" | wc -l)
    $COMPOSE up -d --no-deps --no-recreate --scale "$svc=$((count + 1))" "$svc"
    new=$($COMPOSE ps -a -q "$svc" | grep -vxF "$old" || true)
    if [ -z "$new" ] || [ "$(printf '%s\n' "$new" | wc -l)" -ne 1 ]; then
        echo "  ✗ $svc: لم تُنشَأ نسخةٌ جديدةٌ واحدة — القديمةُ ما زالت تخدم" >&2
        exit 1
    fi
    while :; do
        # الحالةُ والفحصُ معاً: حاويةٌ تنهارُ عندَ الإقلاعِ تدورُ في `restarting`
        # (سياسةُ `unless-stopped`) وفحصُها عالقٌ على `starting` — فالفحصُ وحدَه
        # يُضيِّعُ المهلةَ كلَّها على صورةٍ ميّتةٍ منذُ ثانيتِها الأولى.
        status=$(docker inspect -f '{{.State.Status}}/{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$new")
        case "$status" in
            running/healthy|running/none) break ;;
            */unhealthy|exited/*|dead/*|restarting/*) waited=9999 ;;
        esac
        if [ "$waited" -ge 300 ]; then
            echo "  ✗ $svc: النسخةُ الجديدةُ لم تصحَّ ($status) — أُزيلَت، والقديمةُ ما زالت تخدم" >&2
            docker logs --tail 40 "$new" >&2 || true
            docker rm -f "$new" >/dev/null
            exit 1
        fi
        sleep 3
        waited=$((waited + 3))
    done
    echo "  ✓ $svc: الجديدةُ سليمةٌ بعدَ ${waited} ثانية"
    sleep 12
    # shellcheck disable=SC2086 # قائمةُ معرّفاتٍ تُفصَلُ عمداً
    docker stop -t 30 $old >/dev/null
    # shellcheck disable=SC2086
    docker rm $old >/dev/null
    echo "  ✓ $svc: أُطفِئَت القديمة"
}

echo "▸ استبدالُ الخلفيّةِ بلا انقطاع"
roll_service backend

echo "▸ استبدالُ الواجهةِ بلا انقطاع"
roll_service frontend

# والعمّالُ الثلاثةُ بـ`up -d` العاديّ: الصورةُ تغيّرت فيُعادُ إنشاؤُهم، وليسَ أمامَهم
# زائرٌ يرى الفجوة. ⚠️ عدا `reverb`: إعادةُ إنشائِه تقطعُ كلَّ سوكِتٍ مفتوح، وpusher-js
# يُعيدُ الاتّصالَ وحدَه خلالَ ثوانٍ (والرسائلُ محفوظةٌ في القاعدة، FR-048) — ثمنٌ
# مقبولٌ ومكتوب. والحصصُ الحيّةُ نفسُها تمرُّ بـLiveKit لا بهذا الخادم فلا تنقطع.
echo "▸ رفعُ العمّال"
$COMPOSE up -d --no-deps horizon scheduler reverb

