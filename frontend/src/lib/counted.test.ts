import { describe, expect, it } from "vitest";

import { counted, type CountedForms } from "./labels";

/*
| تمييزُ العددِ — «٢ مدرّس متاح» (٢٠٢٦-٠٩-١١).
|
| ⚠️ والحدودُ هي كلُّ ما يُقاسُ هنا. سلَّمٌ يدويٌّ من نوعِ `count <= 10` يوافقُ
| القاعدةَ الصحيحةَ في الأرقامِ الصغيرةِ ويفارقُها فوقَ المئة: ١٠٣ «قليل»
| و١١١ «كثير»، لأنّ الرتبةَ تُقرَّرُ بآخرِ رقمَين لا بحجمِ العدد. فاختبارٌ
| يقفُ عندَ ١٢ يمرُّ على تنفيذٍ غلطٍ فوقَ المئة.
*/

const TEACHERS: CountedForms = {
  one: "مدرّس متاح",
  two: "مدرّسان متاحان",
  few: "مدرّسين متاحين",
  many: "مدرّساً متاحاً",
};

describe("counted", () => {
  it.each([
    [0, "لا مدرّسين متاحين"],
    [1, "مدرّس متاح"],
    [2, "مدرّسان متاحان"],
    [3, "٣ مدرّسين متاحين"],
    [10, "١٠ مدرّسين متاحين"],
    [11, "١١ مدرّساً متاحاً"],
    [99, "٩٩ مدرّساً متاحاً"],
    // ⚠️ الحدُّ الذي يسقطُ فيه السلَّمُ اليدويّ: ١٠٠ و١٠١ و١٠٢ مفردٌ، ثمّ ١٠٣
    // يعودُ إلى الجمع، و١١١ إلى المفردِ المنصوب.
    [100, "١٠٠ مدرّس متاح"],
    [102, "١٠٢ مدرّس متاح"],
    [103, "١٠٣ مدرّسين متاحين"],
    [111, "١١١ مدرّساً متاحاً"],
    [200, "٢٠٠ مدرّس متاح"],
  ])("%i", (count, expected) => {
    expect(counted(count, TEACHERS)).toBe(expected);
  });

  it("لا يسبقُ المفردَ ولا المثنّى برقم", () => {
    /*
      العربيّةُ تحملُ العددَ في الكلمةِ نفسِها، فـ«٢ مدرّسان» تلعثمٌ لا عدّ.
      والقرارُ في الدالّةِ لا عندَ المُنادي: لو تُرِكَ له لمرَّرَ الثاني عبارةً
      فيها رقمٌ أصلاً، وعادتِ القاعدةُ تُهجّى مرّتَين.
    */
    expect(counted(1, TEACHERS)).not.toMatch(/[٠-٩0-9]/);
    expect(counted(2, TEACHERS)).not.toMatch(/[٠-٩0-9]/);
  });

  it("يقبلُ صيغتَي الصفرِ والمئةِ حين تُذكَران", () => {
    const seats: CountedForms = {
      zero: "لا مقاعد متاحة",
      one: "مقعد واحد متبقٍ",
      two: "مقعدان متبقّيان",
      few: "مقاعد متبقّية",
      many: "مقعداً متبقّياً",
      other: "مقعد متبقٍّ",
    };

    expect(counted(0, seats)).toBe("لا مقاعد متاحة");
    expect(counted(100, seats)).toBe("١٠٠ مقعد متبقٍّ");
  });
});
