import { describe, expect, it } from "vitest";

import { counted, NOUNS, UNREAD_NOTIFICATIONS, type CountedForms } from "./labels";

/*
| تمييزُ العددِ — «٢ مدرّس متاح» (٢٠٢٦-٠٩-١١).
|
| ⚠️ والحدودُ هي كلُّ ما يُقاسُ هنا. سلَّمٌ يدويٌّ من نوعِ `count <= 10` يوافقُ
| القاعدةَ الصحيحةَ في الأرقامِ الصغيرةِ ويفارقُها فوقَ المئة: ١٠٣ «قليل»
| و١١١ «كثير»، لأنّ الرتبةَ تُقرَّرُ بآخرِ رقمَين لا بحجمِ العدد. فاختبارٌ
| يقفُ عندَ ١٢ يمرُّ على تنفيذٍ غلطٍ فوقَ المئة.
*/

const TEACHERS: CountedForms = {
  one: "مدرّس متاح",
  two: "مدرّسان متاحان",
  few: "مدرّسين متاحين",
  many: "مدرّساً متاحاً",
  other: "مدرّس متاح",
};

describe("counted", () => {
  it.each([
    [0, "لا مدرّسين متاحين"],
    [1, "مدرّس متاح"],
    [2, "مدرّسان متاحان"],
    [3, "3 مدرّسين متاحين"],
    [10, "10 مدرّسين متاحين"],
    [11, "11 مدرّساً متاحاً"],
    [99, "99 مدرّساً متاحاً"],
    // ⚠️ الحدُّ الذي يسقطُ فيه السلَّمُ اليدويّ: ١٠٠ و١٠١ و١٠٢ مفردٌ، ثمّ ١٠٣
    // يعودُ إلى الجمع، و١١١ إلى المفردِ المنصوب.
    [100, "100 مدرّس متاح"],
    [102, "102 مدرّس متاح"],
    [103, "103 مدرّسين متاحين"],
    [111, "111 مدرّساً متاحاً"],
    [200, "200 مدرّس متاح"],
  ])("%i", (count, expected) => {
    expect(counted(count, TEACHERS)).toBe(expected);
  });

  it("لا يسبقُ المفردَ ولا المثنّى برقم", () => {
    /*
      العربيّةُ تحملُ العددَ في الكلمةِ نفسِها، فـ«٢ مدرّسان» تلعثمٌ لا عدّ.
      والقرارُ في الدالّةِ لا عندَ المُنادي: لو تُرِكَ له لمرَّرَ الثاني عبارةً
      فيها رقمٌ أصلاً، وعادتِ القاعدةُ تُهجّى مرّتَين.
    */
    expect(counted(1, TEACHERS)).not.toMatch(/[٠-٩0-9]/);
    expect(counted(2, TEACHERS)).not.toMatch(/[٠-٩0-9]/);
  });

  it("لا يُلحِقُ «واحد» برقم", () => {
    /*
      ⚠️ الحدُّ الذي سقطَ فيه أوّلُ تنفيذ. حينَ كانَ `other` يسقطُ إلى `one`،
      وثلاثةُ مُنادِينَ يكتبونَ «حصة واحدة» و«درس واحد» و«طالب واحد»، كانتِ المئةُ
      تُطبَعُ «١٠٠ طالب واحد» — أسوأَ ممّا كان قبلَ الإصلاح. فصارَ `other`
      مطلوباً، وهذا الاختبارُ يُثبِتُ أنّ الرتبتَينِ كلمتانِ مختلفتان.
    */
    const students = {
      one: "طالب واحد",
      two: "طالبان",
      few: "طلاب",
      many: "طالباً",
      other: "طالب",
    };

    expect(counted(1, students)).toBe("طالب واحد");
    expect(counted(100, students)).toBe("100 طالب");
  });

  it("يقبلُ صيغةَ الصفرِ حين تُذكَر", () => {
    const seats: CountedForms = {
      zero: "لا مقاعد متاحة",
      one: "مقعد واحد متبقٍ",
      two: "مقعدان متبقّيان",
      few: "مقاعد متبقّية",
      many: "مقعداً متبقّياً",
      other: "مقعد متبقٍّ",
    };

    expect(counted(0, seats)).toBe("لا مقاعد متاحة");
    expect(counted(100, seats)).toBe("100 مقعد متبقٍّ");
  });
});

/*
| The shared noun sets. A typo in one of them is a typo on every screen that
| counts that noun, so each is read at the four bands once, here.
*/
describe("NOUNS", () => {
  it.each([
    ["minutes", ["دقيقة واحدة", "دقيقتان", "3 دقائق", "11 دقيقة"]],
    ["hours", ["ساعة واحدة", "ساعتان", "3 ساعات", "11 ساعة"]],
    ["days", ["يوم واحد", "يومان", "3 أيام", "11 يوماً"]],
    ["sessions", ["حصة واحدة", "حصتان", "3 حصص", "11 حصة"]],
    ["questions", ["سؤال واحد", "سؤالان", "3 أسئلة", "11 سؤالاً"]],
    ["attempts", ["محاولة واحدة", "محاولتان", "3 محاولات", "11 محاولة"]],
    ["courses", ["كورس واحد", "كورسان", "3 كورسات", "11 كورساً"]],
    ["assignments", ["واجب واحد", "واجبان", "3 واجبات", "11 واجباً"]],
    ["students", ["طالب واحد", "طالبان", "3 طلاب", "11 طالباً"]],
    ["seatsAvailable", ["مقعد واحد متاح", "مقعدان متاحان", "3 مقاعد متاحة", "11 مقعداً متاحاً"]],
  ] as const)("%s", (noun, expected) => {
    expect([1, 2, 3, 11].map((n) => counted(n, NOUNS[noun]))).toEqual(expected);
  });

  it("the unread notifications heading", () => {
    expect([1, 2, 3, 11].map((n) => counted(n, UNREAD_NOTIFICATIONS))).toEqual([
      "إشعار واحد غير مقروء",
      "إشعاران غير مقروءين",
      "3 إشعارات غير مقروءة",
      "11 إشعاراً غير مقروء",
    ]);
  });
});
