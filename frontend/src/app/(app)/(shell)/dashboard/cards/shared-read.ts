/**
 * قراءةٌ واحدةٌ يقرؤُها كرتانِ على اللوحة (٠٢٩ · `FR-018` · `US4`).
 *
 * ⚠️ **الرسمُ يقرأُ الأرقامَ التي يقرؤُها الجدولُ فوقَه، لا أرقاماً مثلَها.**
 * قراءتانِ لنفسِ المسارِ بعدَ لحظةٍ من بعضِهما تُجيبانِ إجابتَينِ مختلفتَينِ
 * أحياناً — حصّةٌ حُجِزَت بينهما، ورقةٌ صُحِّحَت — فيقولُ الجدولُ خمساً ويرسمُ
 * الرسمُ ستّاً على شاشةٍ واحدة، بلا خطأٍ في أيِّ مكان.
 *
 * ⚠️ **وهو «طلبٌ واحدٌ في الجوّ»، لا ذاكرةُ تخزين.** المدخلُ يُحذَفُ لحظةَ استقرارِ
 * الوعد، فالمكسبُ محصورٌ في المُنادينَ الذين طلبوا معاً — وهو بالضبطِ ما يحدثُ
 * حينَ تُصيَّرُ البطاقتانِ في تمريرةٍ واحدة. وذاكرةٌ تبقى بعدَ الاستقرارِ كانت
 * ستُعيدُ جوابَ الدقيقةِ الماضيةِ لبطاقةٍ رُكِّبَت الآن، وستُسرِّبُ حالةَ اختبارٍ
 * إلى الذي يليه — و`vi.clearAllMocks()` لا يراها.
 *
 * والسابقةُ في هذا المستودعِ `lib/echo.ts`: وعدٌ مُذكَّرٌ ينتظرُه كلُّ مُنادٍ
 * مهما وصلَ متى — كُتِبَ هناك لأنّ عَلَماً منطقيّاً كان يُجيبُ الثانيَ `null`.
 */
const inFlight = new Map<string, Promise<unknown>>();

export function sharedRead<T>(key: string, fetcher: () => Promise<T>): Promise<T> {
  const running = inFlight.get(key);

  if (running !== undefined) return running as Promise<T>;

  // ⚠️ الحذفُ في `finally` لا في `then`: وعدٌ مرفوضٌ يبقى في الخريطةِ إلى الأبد،
  // فـ«إعادةُ المحاولة» تُعيدُ الرفضَ نفسَه بلا طلب.
  const request = fetcher().finally(() => inFlight.delete(key));

  inFlight.set(key, request);

  return request;
}
